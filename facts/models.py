from django.db import models


class Place(models.Model):
    """A point of interest along the line (building, monument, street, square...)."""

    name = models.CharField(max_length=200)
    lat = models.FloatField()
    lon = models.FloatField()
    category = models.CharField(max_length=50, blank=True)  # e.g. history, architecture, street-name
    image_url = models.URLField(blank=True)

    class Meta:
        indexes = [models.Index(fields=["lat", "lon"])]

    def __str__(self):
        return self.name


class Fact(models.Model):
    """A short "did you know" text about a place. Generated by AI from a source, then reviewed."""

    place = models.ForeignKey(Place, on_delete=models.CASCADE, related_name="facts")
    title = models.CharField(max_length=200)
    text = models.TextField()
    language = models.CharField(max_length=5, default="pl")
    source_url = models.URLField(blank=True)  # always keep where the fact came from
    generated_by = models.CharField(max_length=50, blank=True)  # model name, or "human"
    approved = models.BooleanField(default=False)  # only approved facts are served
    priority = models.IntegerField(default=0)  # higher = more surprising, shown first
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return self.title


class SeenFact(models.Model):
    """Which facts an anonymous device has already seen, so regulars get new ones."""

    device_id = models.CharField(max_length=64, db_index=True)
    fact = models.ForeignKey(Fact, on_delete=models.CASCADE)
    seen_at = models.DateTimeField(auto_now_add=True)
    vehicle_number = models.CharField(max_length=20, blank=True)

    class Meta:
        unique_together = ("device_id", "fact")

    def __str__(self):
        return f"{self.device_id[:8]} saw fact {self.fact_id}"
